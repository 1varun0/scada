"""
Parses pytest verbose log files and generates markdown tables for test suites.
Usage:
    python results_v2/scripts/parse_test_results.py
"""
import re
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
RAW_DIR = REPO_ROOT / "results_v2" / "raw"
TABLES_DIR = REPO_ROOT / "results_v2" / "tables"


def parse_pytest_log(log_path: Path):
    if not log_path.exists():
        raise FileNotFoundError(f"Log not found: {log_path}")

    text = log_path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()

    test_pattern = re.compile(r"^(\S+::\S+)\s+(PASSED|FAILED|SKIPPED|XFAIL|XPASS|ERROR)")
    duration_pattern = re.compile(r"^\s*([0-9\.]+)s\s+(\w+)\s+(\S+)")
    summary_pattern = re.compile(r"=+\s*(?:(\d+)\s+passed)?(?:,\s*(\d+)\s+skipped)?(?:,\s*(\d+)\s+failed)?(?:,\s*(\d+)\s+errors?)?\s+in\s+([0-9\.]+)s")

    tests = []
    durations = []
    in_durations = False
    summary_info = {}

    for line in lines:
        m_test = test_pattern.match(line)
        if m_test:
            test_id, outcome = m_test.groups()
            file_path = test_id.split("::")[0]
            tests.append({
                "test_id": test_id,
                "file": file_path,
                "outcome": outcome
            })
            continue

        if "slowest" in line and "durations" in line:
            in_durations = True
            continue

        if in_durations:
            m_dur = duration_pattern.match(line)
            if m_dur:
                sec, stage, test_id = m_dur.groups()
                durations.append({
                    "duration_s": float(sec),
                    "stage": stage,
                    "test_id": test_id
                })
            elif line.startswith("=") and "in" in line:
                in_durations = False

        if line.startswith("=") and ("passed" in line or "failed" in line) and "in" in line:
            # e.g. "=== 66 passed in 3.65s ===" or "=== 116 passed in 314.58s ==="
            summary_info["raw_summary"] = line.strip("= ")

    # Compute stats
    by_file = {}
    for t in tests:
        f = t["file"]
        if f not in by_file:
            by_file[f] = {"total": 0, "passed": 0, "failed": 0, "skipped": 0}
        by_file[f]["total"] += 1
        outcome = t["outcome"].lower()
        if outcome == "passed":
            by_file[f]["passed"] += 1
        elif outcome == "failed":
            by_file[f]["failed"] += 1
        elif outcome == "skipped":
            by_file[f]["skipped"] += 1

    return {
        "tests": tests,
        "by_file": by_file,
        "durations": durations,
        "total_collected": len(tests),
        "total_passed": sum(1 for t in tests if t["outcome"] == "PASSED"),
        "total_failed": sum(1 for t in tests if t["outcome"] == "FAILED"),
        "total_skipped": sum(1 for t in tests if t["outcome"] == "SKIPPED"),
        "summary_info": summary_info
    }


def main():
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", type=int, default=1, choices=[1, 2], help="Run number (1 or 2)")
    args = parser.parse_args()
    run_num = args.run

    TABLES_DIR.mkdir(parents=True, exist_ok=True)

    prefix = f"b{run_num}_pytest"
    batch_log = RAW_DIR / f"{prefix}_tests_run{run_num}.log"
    batch_json = RAW_DIR / f"{prefix}_tests_run{run_num}.json"
    live_log = RAW_DIR / f"{prefix}_scada_live_tests_run{run_num}.log"
    live_json = RAW_DIR / f"{prefix}_scada_live_tests_run{run_num}.json"

    batch_meta = json.loads(batch_json.read_text(encoding="utf-8")) if batch_json.exists() else {}
    live_meta = json.loads(live_json.read_text(encoding="utf-8")) if live_json.exists() else {}

    batch_res = parse_pytest_log(batch_log) if batch_log.exists() else None
    live_res = parse_pytest_log(live_log) if live_log.exists() else None

    # Save aggregated parsed json
    parsed_combined = {
        "batch": {"meta": batch_meta, "results": batch_res},
        "live": {"meta": live_meta, "results": live_res}
    }
    (RAW_DIR / f"parsed_test_suites_run{run_num}.json").write_text(json.dumps(parsed_combined, indent=2), encoding="utf-8")

    # Generate markdown table
    md_lines = [
        f"# Table T01: Test Suites Execution Summary (Run {run_num})",
        "",
        f"> Generated by `results_v2/scripts/parse_test_results.py --run {run_num}` from raw execution logs:",
        f"> - Batch Suite: `{batch_log.name}` (sidecar `{batch_json.name}`)",
        f"> - Live Suite: `{live_log.name}` (sidecar `{live_json.name}`)",
        "",
        "## Overall Suite Execution",
        "",
        "| Suite Name | Target Directory | Tests Collected | Passed | Failed | Skipped | Exit Code | Wall Time (s) | Raw Log Citation |",
        "| :--- | :--- | :---: | :---: | :---: | :---: | :---: | :---: | :--- |"
    ]

    if batch_res:
        md_lines.append(
            f"| Core Batch Suite | `tests/` | {batch_res['total_collected']} | {batch_res['total_passed']} | "
            f"{batch_res['total_failed']} | {batch_res['total_skipped']} | {batch_meta.get('exit_code', 0)} | "
            f"{batch_meta.get('duration_s', 'N/A')}s | [`{batch_log.name}`](../raw/{batch_log.name}) |"
        )
    if live_res:
        md_lines.append(
            f"| Live & Gateway Suite | `scada_live/tests/` | {live_res['total_collected']} | {live_res['total_passed']} | "
            f"{live_res['total_failed']} | {live_res['total_skipped']} | {live_meta.get('exit_code', 0)} | "
            f"{live_meta.get('duration_s', 'N/A')}s | [`{live_log.name}`](../raw/{live_log.name}) |"
        )
    if batch_res and live_res:
        tot_tests = batch_res['total_collected'] + live_res['total_collected']
        tot_pass = batch_res['total_passed'] + live_res['total_passed']
        tot_fail = batch_res['total_failed'] + live_res['total_failed']
        tot_skip = batch_res['total_skipped'] + live_res['total_skipped']
        b_time = batch_meta.get('duration_s', 0.0)
        l_time = live_meta.get('duration_s', 0.0)
        tot_time = round(b_time + l_time, 2)
        md_lines.append(
            f"| **Combined Total** | **Both Suites** | **{tot_tests}** | **{tot_pass}** | **{tot_fail}** | **{tot_skip}** | **0** | **{tot_time}s** | - |"
        )

    md_lines.extend([
        "",
        "## Detailed Breakdown by Test Module",
        "",
        "### Core Batch Suite (`tests/`)",
        "",
        "| Test File | Total Tests | Passed | Failed | Skipped | Status |",
        "| :--- | :---: | :---: | :---: | :---: | :---: |"
    ])

    if batch_res:
        for f, s in sorted(batch_res["by_file"].items()):
            status = "✅ PASS" if s["failed"] == 0 and s["passed"] == s["total"] else "❌ FAIL"
            md_lines.append(f"| `{f}` | {s['total']} | {s['passed']} | {s['failed']} | {s['skipped']} | {status} |")

    md_lines.extend([
        "",
        "### Live Streaming & Prevention Suite (`scada_live/tests/`)",
        "",
        "| Test File | Total Tests | Passed | Failed | Skipped | Status |",
        "| :--- | :---: | :---: | :---: | :---: | :---: |"
    ])

    if live_res:
        for f, s in sorted(live_res["by_file"].items()):
            status = "✅ PASS" if s["failed"] == 0 and s["passed"] == s["total"] else "❌ FAIL"
            md_lines.append(f"| `{f}` | {s['total']} | {s['passed']} | {s['failed']} | {s['skipped']} | {status} |")

    # Top slowest tests
    md_lines.extend([
        "",
        "## Slowest Test Durations (Top Recorded)",
        "",
        "| Suite | Duration (s) | Phase / Stage | Test Identifier |",
        "| :--- | :---: | :---: | :--- |"
    ])

    all_durations = []
    if batch_res:
        for d in batch_res.get("durations", []):
            all_durations.append({"suite": "tests/", **d})
    if live_res:
        for d in live_res.get("durations", []):
            all_durations.append({"suite": "scada_live/tests/", **d})

    all_durations.sort(key=lambda x: x["duration_s"], reverse=True)
    for d in all_durations[:20]:
        md_lines.append(f"| `{d['suite']}` | {d['duration_s']:.2f}s | {d['stage']} | `{d['test_id']}` |")

    out_file = TABLES_DIR / "t01_test_suites_summary.md"
    out_file.write_text("\n".join(md_lines) + "\n", encoding="utf-8")
    print(f"Generated {out_file} successfully.")


if __name__ == "__main__":
    main()
