"""
Compares Run 1 and Run 2 test execution outputs for determinism verification.
Usage:
    python results_v2/scripts/compare_test_runs.py
"""
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
RAW_DIR = REPO_ROOT / "results_v2" / "raw"
AUDIT_DIR = REPO_ROOT / "results_v2" / "_audit"


def load_parsed_run(run_num: int):
    p = RAW_DIR / f"parsed_test_suites_run{run_num}.json"
    if not p.exists():
        raise FileNotFoundError(f"Missing {p}")
    return json.loads(p.read_text(encoding="utf-8"))


def main():
    AUDIT_DIR.mkdir(parents=True, exist_ok=True)

    run1 = load_parsed_run(1)
    run2 = load_parsed_run(2)

    lines = [
        "# Test Suite Determinism Audit: Run 1 vs Run 2",
        "",
        "> Generated by `results_v2/scripts/compare_test_runs.py`",
        "",
        "## Summary of Runs",
        "",
        "| Suite | Run | Total Tests | Passed | Failed | Skipped | Exit Code | Wall Time (s) |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: |"
    ]

    for suite_key, name in [("batch", "Core Batch (tests/)"), ("live", "Live & Gateway (scada_live/tests/)")]:
        r1_meta = run1[suite_key]["meta"]
        r1_res = run1[suite_key]["results"]
        r2_meta = run2[suite_key]["meta"]
        r2_res = run2[suite_key]["results"]

        lines.append(
            f"| {name} | Run 1 | {r1_res['total_collected']} | {r1_res['total_passed']} | "
            f"{r1_res['total_failed']} | {r1_res['total_skipped']} | {r1_meta.get('exit_code', 0)} | "
            f"{r1_meta.get('duration_s', 'N/A')}s |"
        )
        lines.append(
            f"| {name} | Run 2 | {r2_res['total_collected']} | {r2_res['total_passed']} | "
            f"{r2_res['total_failed']} | {r2_res['total_skipped']} | {r2_meta.get('exit_code', 0)} | "
            f"{r2_meta.get('duration_s', 'N/A')}s |"
        )

    # Outcome comparison
    lines.extend([
        "",
        "## Item-Level Determinism Verification",
        ""
    ])

    all_identical = True
    for suite_key, name in [("batch", "Core Batch (tests/)"), ("live", "Live & Gateway (scada_live/tests/)")]:
        r1_tests = {t["test_id"]: t["outcome"] for t in run1[suite_key]["results"]["tests"]}
        r2_tests = {t["test_id"]: t["outcome"] for t in run2[suite_key]["results"]["tests"]}

        diffs = []
        for tid, o1 in r1_tests.items():
            o2 = r2_tests.get(tid)
            if o1 != o2:
                diffs.append((tid, o1, o2))
        
        missing_in_r2 = set(r1_tests.keys()) - set(r2_tests.keys())
        extra_in_r2 = set(r2_tests.keys()) - set(r1_tests.keys())

        if not diffs and not missing_in_r2 and not extra_in_r2:
            lines.append(f"- **{name}**: 100% Deterministic. All {len(r1_tests)} test outcomes are bit-for-bit identical across runs.")
        else:
            all_identical = False
            lines.append(f"- **{name}**: DISCREPANCIES DETECTED:")
            for tid, o1, o2 in diffs:
                lines.append(f"  - `{tid}`: Run 1 = {o1}, Run 2 = {o2}")
            for m in missing_in_r2:
                lines.append(f"  - `{m}` present in Run 1 but missing in Run 2")
            for e in extra_in_r2:
                lines.append(f"  - `{e}` present in Run 2 but missing in Run 1")

    lines.extend([
        "",
        f"**Overall Verdict**: {'✅ 100% DETERMINISTIC REPRODUCTION' if all_identical else '⚠️ NON-DETERMINISTIC BEHAVIOR DETECTED'}",
        ""
    ])

    out_file = AUDIT_DIR / "determinism.md"
    out_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {out_file} successfully.")


if __name__ == "__main__":
    main()
