"""
SCADA IDS — MATLAB CSV to SQLite Importer

Reads all CSV files generated by MATLAB's run_all_scenarios.m
and inserts them into the SQLite database (scada_ids.db).

This is the bridge between MATLAB (physics simulation) and
Python (AI engines, evaluation, dashboard).

Usage:
    python scripts/import_matlab_csv.py
    python scripts/import_matlab_csv.py --csv-dir path/to/csvs
    python scripts/import_matlab_csv.py --db-path path/to/scada_ids.db
"""

import sys
import os
import glob
import argparse
import pandas as pd

# Add project root to path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from storage.sqlite_client import SCADADatabase


# Column mapping: CSV column name → SQLite column name
# MATLAB writetable uses the variable names we set in the table
CSV_TO_DB_COLUMNS = {
    'scenario_id': 'scenario_id',
    'sequence_id': 'sequence_id',
    'simulation_time_s': 'simulation_time_s',
    'source_time_s': 'source_time_s',
    'data_age_ms': 'data_age_ms',
    'packet_received': 'packet_received',
    'communication_status': 'communication_status',
    'operating_condition': 'operating_condition',
    'tank_level_setpoint': 'tank_level_setpoint',
    'tank_level_observed': 'tank_level_observed',
    'q_in': 'q_in',
    'q_out': 'q_out',
    'pump_command': 'pump_command',
    'pump_state': 'pump_state',
    'valve_command': 'valve_command',
    'valve_state': 'valve_state',
    'control_command': 'control_command',
    'user_id': 'user_id',
    'user_role': 'user_role',
    'is_authenticated': 'is_authenticated',
    'is_authorized': 'is_authorized',
    'attack_type': 'attack_type',
    'attack_parameter': 'attack_parameter',
    'ground_truth': 'ground_truth',
    'replay_source_sequence_id': 'replay_source_sequence_id',
}

TELEMETRY_COLUMNS = list(CSV_TO_DB_COLUMNS.values())

ATTACK_META_COLUMNS = [
    'scenario_id', 'attack_id', 'attack_type',
    'attack_start_time_s', 'attack_end_time_s',
    'attack_parameter_type', 'attack_parameter_value',
    'random_seed', 'description',
    'operating_condition', 'initial_tank_level',
]


def import_telemetry_csvs(csv_dir: str, db: SCADADatabase, verbose: bool = True) -> int:
    """Import all scenario CSV files into the scada_telemetry table.

    Args:
        csv_dir: Directory containing CSV files (N_001.csv, A1_001.csv, etc.)
        db: Open SCADADatabase instance.
        verbose: Print progress.

    Returns:
        Total number of records imported.
    """
    # Find all scenario CSVs (exclude attack_scenarios.csv metadata)
    csv_files = sorted(glob.glob(os.path.join(csv_dir, '*.csv')))
    csv_files = [f for f in csv_files if os.path.basename(f) != 'attack_scenarios.csv']

    if not csv_files:
        print(f"ERROR: No CSV files found in {csv_dir}")
        return 0

    total_records = 0

    for i, csv_path in enumerate(csv_files):
        filename = os.path.basename(csv_path)
        scenario_id = os.path.splitext(filename)[0]

        try:
            df = pd.read_csv(csv_path)

            # Handle NaN values for SQLite compatibility
            df = df.where(pd.notnull(df), None)

            # Convert to list of dicts
            records = []
            for _, row in df.iterrows():
                record = {}
                for csv_col, db_col in CSV_TO_DB_COLUMNS.items():
                    if csv_col in df.columns:
                        val = row[csv_col]
                        # Convert numpy types to Python native types
                        if pd.isna(val):
                            record[db_col] = None
                        elif isinstance(val, (int, float)):
                            record[db_col] = int(val) if db_col in (
                                'sequence_id', 'data_age_ms', 'packet_received',
                                'pump_command', 'pump_state', 'ground_truth',
                                'is_authenticated', 'is_authorized',
                                'replay_source_sequence_id'
                            ) and not pd.isna(val) else val
                        else:
                            record[db_col] = str(val)
                    else:
                        record[db_col] = None
                records.append(record)

            db.insert_telemetry_batch(records)
            total_records += len(records)

            if verbose:
                print(f"  [{i+1}/{len(csv_files)}] {filename}: {len(records)} records")

        except Exception as e:
            print(f"  ERROR reading {filename}: {e}")

    return total_records


def import_attack_metadata(csv_dir: str, db: SCADADatabase, verbose: bool = True) -> int:
    """Import attack_scenarios.csv into the attack_scenarios table.

    Args:
        csv_dir: Directory containing attack_scenarios.csv.
        db: Open SCADADatabase instance.
        verbose: Print progress.

    Returns:
        Number of attack records imported.
    """
    meta_path = os.path.join(csv_dir, 'attack_scenarios.csv')
    if not os.path.exists(meta_path):
        if verbose:
            print("  No attack_scenarios.csv found (normal-only run?)")
        return 0

    df = pd.read_csv(meta_path)
    count = 0

    for _, row in df.iterrows():
        record = {}
        for col in ATTACK_META_COLUMNS:
            if col in df.columns:
                val = row[col]
                record[col] = None if pd.isna(val) else val
            else:
                record[col] = None
        db.insert_attack_scenario(record)
        count += 1

    if verbose:
        print(f"  Attack metadata: {count} records")

    return count


def main():
    parser = argparse.ArgumentParser(
        description='Import MATLAB-generated CSV files into SQLite database'
    )
    parser.add_argument(
        '--csv-dir',
        default=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                             'matlab', 'data'),
        help='Directory containing MATLAB CSV files (default: matlab/data/)'
    )
    parser.add_argument(
        '--db-path',
        default=None,
        help='Path to SQLite database (default: data/scada_ids.db)'
    )
    parser.add_argument(
        '--clear',
        action='store_true',
        help='Clear existing data before import'
    )

    args = parser.parse_args()

    print("=" * 60)
    print("  SCADA IDS - MATLAB CSV to SQLite Importer")
    print("=" * 60)
    print(f"  CSV directory: {args.csv_dir}")

    # Open database
    db = SCADADatabase(db_path=args.db_path)
    db.connect()
    db.initialize()

    print(f"  Database: {db._db_path}")
    print(f"  WAL mode: {db.get_wal_mode()}")
    print("-" * 60)

    if args.clear:
        print("  Clearing existing data...")
        db.clear_all()

    # Import telemetry
    print("\nImporting telemetry CSVs...")
    n_telemetry = import_telemetry_csvs(args.csv_dir, db, verbose=True)

    # Import attack metadata
    print("\nImporting attack metadata...")
    n_attacks = import_attack_metadata(args.csv_dir, db, verbose=True)

    # Summary
    print("\n" + "=" * 60)
    print(f"  Total telemetry records: {n_telemetry:,}")
    print(f"  Total attack metadata:   {n_attacks}")
    print(f"  Unique scenarios:        {len(db.get_scenario_ids())}")
    print(f"  Normal scenarios:        {len(db.get_scenario_ids('None'))}")
    attack_types = ['FDI', 'Replay', 'DoS', 'Auth_Misuse']
    for at in attack_types:
        count = len(db.get_scenario_ids(at))
        if count > 0:
            print(f"  {at} scenarios:       {count}")
    print("=" * 60)

    db.close()
    print("\nDone. Database ready for Python pipeline.")


if __name__ == "__main__":
    main()
